"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const css = fs.readFileSync(path.join(root, "css/styles.css"), "utf8");
const startCss = fs.readFileSync(path.join(root, "css/startseite.css"), "utf8");
const nav = fs.readFileSync(path.join(root, "js/navigation.js"), "utf8");
const start = fs.readFileSync(path.join(root, "js/startseite.js"), "utf8");
assert(css.includes("grid-template-columns: 17rem minmax(0, 1fr)"), "desktop allocates distinct navigation and content columns");
assert(css.includes(".kopf { grid-column: 1 / -1; grid-row: 1;"), "header spans the full desktop window above navigation");
assert(css.includes("main, .fuss, .schritte, .rueckzeile { grid-column: 2;"), "content is placed beside navigation in the remaining column");
assert(css.includes("padding-left: 2rem; padding-right: 2rem"), "content has clear horizontal gutters");
assert(startCss.includes(".startseite { max-width: none; margin: 0; padding: 0; }"), "no nested centered homepage width");
assert(!/(?:^|[}\n])\s*(?:body|main|\.kopf|\.startseite)[^{]*\{[^}]*overflow\s*:\s*hidden/s.test(css), "page content is not concealed by hidden overflow");
assert(nav.includes("aria-label", nav.indexOf("Abgeschlossen")) || nav.includes("LERNFORTSCHRITT.abschlusszeichen"), "navigation renders accessible completion marker");
assert(start.includes("data-progress-id") && start.includes("LERNFORTSCHRITT.abgeschlossen(u.id)"), "overview topic card uses topic progress id");

const values = new Map();
const document = { createElement(tag) { return { tagName: tag.toUpperCase(), attrs: {}, setAttribute(k,v){this.attrs[k]=v;}, className:"", textContent:"" }; } };
const window = { localStorage: { getItem(k){return values.has(k)?values.get(k):null;} }, document, Event: class Event {}, dispatchEvent(){} };
const context = { window, document, globalThis: window, Event: window.Event };
vm.runInNewContext(fs.readFileSync(path.join(root,"js/fortschritt.js"),"utf8"), context);
const api = window.LERNFORTSCHRITT;
assert.equal(api.abgeschlossen("computer-grundlagen"), false, "empty progress is not complete");
const computer = {abschlussGesehen:true,karten:{computer:true,bildschirm:true,tastatur:true,maus:true,netzwerk:true},uebung:{"u-tastatur":"eingabe","u-bildschirm":"ausgabe","u-computer":"verarbeitung","u-maus":"eingabe","u-drucker":"ausgabe"},quiz:{q1:1,q2:0,q3:1,q4:0,q5:1}};
values.set("it-ausbildung.computer-grundlagen.v1",JSON.stringify(computer));
assert.equal(api.abgeschlossen("computer-grundlagen"), true, "all lesson tasks and viewed conclusion yield complete status");
computer.quiz.q5=0; values.set("it-ausbildung.computer-grundlagen.v1",JSON.stringify(computer));
assert.equal(api.abgeschlossen("computer-grundlagen"), false, "wrong quiz answer prevents false completion");
const network={abschlussGesehen:true,eigeneGueltig:true,antworten:{anzahl:1,wertebereich:2,gueltig:0}};
values.set("it-ausbildung.netzwerkgrundlagen.v1",JSON.stringify(network));
assert.equal(api.abgeschlossen("lf3-ipv4"), true, "IPv4 lesson completion derives from its existing lesson store");
assert.equal(api.abgeschlossen("lf3"), false, "lesson never marks whole learning field complete");
values.delete("it-ausbildung.netzwerkgrundlagen.v1");
assert.equal(api.abgeschlossen("lf3-ipv4"), false, "reset/removed progress clears topic status");
const marker=api.abschlusszeichen();
assert.equal(marker.textContent,"✓"); assert.equal(marker.attrs["aria-label"],"Abgeschlossen");
console.log("fortschritt.test.js: all assertions passed");
