"use strict";
const fs=require("node:fs"), path=require("node:path"), assert=require("node:assert/strict");
const root=path.resolve(__dirname,".."); global.window=global; require(path.join(root,"js/glossar-daten.js"));
const lesson=require(path.join(root,"js/lf1-ausbildungsbetrieb.js"));
const html=fs.readFileSync(path.join(root,"module/lf1-ausbildungsbetrieb.html"),"utf8");
assert.equal(lesson.STEPS.join(","),"start,rollen,uebung,abschluss");
assert.equal(lesson.QUESTIONS.length,3);
lesson.QUESTIONS.forEach(q=>{assert.equal(q.options.filter(o=>o.value===q.correct).length,1);q.options.forEach(o=>assert(o.feedback.length>20));});
assert.equal(lesson.progress({answers:{},finish:false}),0);
assert(lesson.progress({answers:{q1:"team"},finish:false})>0);
assert.equal(lesson.progress({answers:{q1:"team",q2:"abstimmen",q3:"betrieb"},finish:true}),100);
assert(!html.includes('type="text"') && !html.includes('type="email"'),"no personal-data input");
assert(/ausdrücklich fiktiv|frei erfunden/i.test(html));
assert(/kein verbindlicher betrieblicher Ausbildungsplan/i.test(html));
assert(/aria-label="Schaubild:[^"]+"/.test(html));
lesson.TERMS.forEach(t=>assert(global.GLOSSAR.some(g=>g.begriff===t),"glossar term missing: "+t));
assert.equal(new Set(global.GLOSSAR.map(g=>g.begriff)).size,global.GLOSSAR.length);
const catalog=fs.readFileSync(path.join(root,"js/module-daten.js"),"utf8");
assert(catalog.includes('id: "lf1-betrieb-aufgaben"')&&fs.existsSync(path.join(root,"module/lf1-ausbildungsbetrieb.html")));
assert(html.includes("../assets/desoworks/logo-orbital-werkstatt.svg")&&html.includes("../js/anzeige-glossar.js"));
console.log("lf1-ausbildungsbetrieb.test.js: PASS — content, progress, glossary, feedback model, privacy and markup");
