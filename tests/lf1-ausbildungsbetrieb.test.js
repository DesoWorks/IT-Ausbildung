const catalog=fs.readFileSync(path.join(root,"js/module-daten.js"),"utf8");
assert(catalog.includes('id: "lf1-betrieb-aufgaben"')&&fs.existsSync(path.join(root,"module/lf1-ausbildungsbetrieb.html")));
assert(html.includes("../assets/desoworks/logo-orbital-werkstatt.svg")&&html.includes("../js/anzeige-glossar.js"));
console.log("lf1-ausbildungsbetrieb.test.js: PASS — content, progress, glossary, feedback model, privacy and markup");
