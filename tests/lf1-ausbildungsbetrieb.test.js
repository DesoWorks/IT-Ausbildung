"use strict";
const fs=require("node:fs"), path=require("node:path"), assert=require("node:assert/strict");
const root=path.resolve(__dirname,".."); global.window=global; require(path.join(root,"js/glossar-daten.js"));
const lesson=require(path.join(root,"js/lf1-ausbildungsbetrieb.js"));
const html=fs.readFileSync(path.join(root,"module/lf1-ausbildungsbetrieb.html"),"utf8");
assert.equal(lesson.STEPS.join(","),"start,rollen,uebung,abschluss");
