assert(/ausdrücklich fiktiv|frei erfunden/i.test(html));
assert(/kein verbindlicher betrieblicher Ausbildungsplan/i.test(html));
assert(/role="img" aria-label="Schaubild von oben nach unten:[^"]+"/.test(html));
assert.match(html,/Schaubild von oben nach unten:[\s\S]*?Betrieb Nordlicht IT-Service[\s\S]*?Abteilung IT-Service[\s\S]*?Support-Team[\s\S]*?Samira als Auszubildende/);
assert.match(html,/class="rollen-pfeil"[^>]*>[\s\S]*?In diesem Beispiel gehört zum Betrieb/);
assert.match(html,/Zu dieser Abteilung gehört/);
assert.match(html,/In diesem Team lernt und arbeitet/);
assert.match(html,/Rolle innerhalb des Teams/);
assert.match(html,/\.rollen-karten \{[^}]*grid-template-columns:minmax\(0,1fr\)/);
assert.match(html,/\.rollen-optionen \{[^}]*grid-template-columns:minmax\(0,1fr\)/);
assert.match(html,/\.rollen-option:focus-within/);
assert.match(html,/\.rollen-option:has\(input:checked\)/);
assert.match(fs.readFileSync(path.join(root,"js/lf1-ausbildungsbetrieb.js"),"utf8"),/input\.type="radio"/);
assert.match(fs.readFileSync(path.join(root,"js/lf1-ausbildungsbetrieb.js"),"utf8"),/Samira richtet im fiktiven Beispiel einen Bildschirm/);
assert.match(html,/Ansprechpersonen bei Unsicherheit/);
assert.match(html,/keine zusätzliche Organisationsebene/);
