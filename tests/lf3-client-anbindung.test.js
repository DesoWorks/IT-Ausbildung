"use strict";
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const lesson = require(path.join(root, "js/lf3-client-anbindung.js"));
const html = fs.readFileSync(path.join(root, "module/lf3-client-anbindung.html"), "utf8");
const catalog = fs.readFileSync(path.join(root, "js/module-daten.js"), "utf8");

assert(fs.existsSync(path.join(root, "module/lf3-client-anbindung.html")));
assert.equal(lesson.ID, "lf3-client-anbindung");
assert.equal(lesson.QUESTIONS.length, 4);
for (const q of lesson.QUESTIONS) {
  assert.equal(q.options.filter(o => o.id === q.correct).length, 1, q.id + " hat genau eine richtige Option");
  assert(q.options.every(o => o.feedback.length > 20), q.id + " erklärt jede Option");
}
assert(html.includes('<body data-page="lf3-client-anbindung"'));
assert(html.includes("Client-Anbindung: vom Anschluss bis zur Verbindung"));
for (const step of ['data-step="start"', 'data-step="case"', 'data-step="exercise"', 'data-step="finish"']) assert(html.includes(step));
assert(html.includes('href="../glossar.html?von=lf3-client-anbindung.html"'));
assert(html.includes("Fiktiver Hinweis"));
assert(html.trim().endsWith("</html>"));
assert(html.indexOf("../js/module-daten.js") < html.indexOf("../js/fortschritt.js"));
assert(html.indexOf("../js/fortschritt.js") < html.indexOf("../js/navigation.js"));
assert(html.indexOf("../js/navigation.js") < html.indexOf("../js/glossar-daten.js"));
assert(html.indexOf("../js/glossar-daten.js") < html.indexOf("../js/anzeige-glossar.js"));
assert(html.indexOf("../js/anzeige-glossar.js") < html.indexOf("../js/version.js"));
assert(html.indexOf("../js/version.js") < html.indexOf("../js/lf3-client-anbindung.js"));
assert.equal(lesson.evaluate({}).empty, lesson.QUESTIONS.length);
assert.equal(lesson.evaluate({}).allCorrect, false);
assert.equal(lesson.evaluate({}).results[0].optionId, "");
const all = Object.fromEntries(lesson.QUESTIONS.map(q => [q.id, q.correct]));
assert.equal(lesson.evaluate(all).correct, lesson.QUESTIONS.length);
assert.equal(lesson.evaluate(all).allCorrect, true);
const wrong = { ...all, q1: lesson.QUESTIONS[0].options.find(o => o.id !== lesson.QUESTIONS[0].correct).id };
assert.equal(lesson.evaluate(wrong).wrong, 1);
assert.equal(lesson.evaluate(wrong).allCorrect, false);
assert(lesson.evaluate(wrong).results[0].feedback.length > 20);
assert.equal(lesson.progress({ checked: true, answers: all, finish: false }), 80);
assert.equal(lesson.progress({ checked: true, answers: all, finish: true }), 100);
assert.equal(lesson.progressText({ checked: true, answers: all, finish: false }), "Fortschritt: 80 %");
assert.equal(lesson.progressText({ checked: true, answers: all, finish: true }), "Fortschritt: 100 %");
assert.equal(lesson.progressText({}), "Fortschritt: 0 %");
assert(html.includes("Fortschritt: 0 %"));
assert(!html.includes("von 5 Schritten"));
const lf3 = catalog.slice(catalog.indexOf('{ id: "lf3"'), catalog.indexOf('{ id: "lf4"'));
assert(lf3.includes('{ id: "lf3-client-anbindung", typ: "lektion", titel: "Client-Anbindung: vom Anschluss bis zur Verbindung"'));
assert(lf3.includes('page: "lf3-client-anbindung", status: "verfuegbar", datei: "module/lf3-client-anbindung.html"'));
assert(catalog.includes('titel: "Netzwerkgrundlagen und Client-Anbindung", status: "kommt-bald"'));
console.log("lf3-client-anbindung.test.js: PASS — HTML, Fortschritt, leerer Check, richtige/falsche Antworten und LF3-Katalog");
