"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const lesson = require(path.join(root, "js/lf3-dhcp.js"));
const html = fs.readFileSync(path.join(root, "module/lf3-dhcp.html"), "utf8");
const catalog = fs.readFileSync(path.join(root, "js/module-daten.js"), "utf8");
const glossary = fs.readFileSync(path.join(root, "js/glossar-daten.js"), "utf8");

assert.equal(lesson.ID, "lf3-dhcp");
assert.equal(lesson.KEY, "it-ausbildung.lf3-dhcp.v1");
assert.deepEqual(lesson.STEPS, ["start", "case", "exercise", "finish"]);
assert.equal(lesson.QUESTIONS.length, 4);
assert(html.includes('<body data-page="lf3-dhcp"'));
assert(html.includes("DHCP: automatische Konfiguration nachvollziehen"));
for (const step of ['data-step="start"', 'data-step="case"', 'data-step="exercise"', 'data-step="finish"']) assert(html.includes(step));
assert(html.includes('href="../glossar.html?von=lf3-dhcp.html"'));
assert(html.includes('href="lf3-ipv4-konfiguration.html"') && html.includes('href="netzwerkgrundlagen.html"'));
assert(html.includes("Fiktiver Hinweis") && html.includes("Mira-01") && html.includes("192.168.10.25"));
assert(html.includes("Fortschritt: 0 %"));
assert(!html.includes("von 5 Schritten"));
assert(!/<input[^>]*\schecked/.test(html), "keine vorausgewählte Antwort");
assert(html.trim().endsWith("</html>"));
const order = ["module-daten", "fortschritt", "navigation", "glossar-daten", "anzeige-glossar", "version", "lf3-dhcp"].map(n => html.indexOf("../js/" + n + ".js"));
assert(order.every((v, i) => v > -1 && (i === 0 || order[i - 1] < v)), "Skriptreihenfolge");
assert.equal(lesson.evaluate({}).empty, lesson.QUESTIONS.length);
assert.equal(lesson.evaluate({}).allCorrect, false);
assert.equal(lesson.evaluate({}).results[0].optionId, "");
const all = Object.fromEntries(lesson.QUESTIONS.map(q => [q.id, q.correct]));
assert.equal(lesson.evaluate(all).correct, lesson.QUESTIONS.length);
assert.equal(lesson.evaluate(all).allCorrect, true);
const wrong = { ...all, q1: lesson.QUESTIONS[0].options.find(o => o.id !== lesson.QUESTIONS[0].correct).id };
assert.equal(lesson.evaluate(wrong).wrong, 1);
assert.equal(lesson.evaluate(wrong).allCorrect, false);
assert(lesson.evaluate(wrong).results[0].feedback.length > 20);
assert.equal(lesson.progress({}), 0);
assert.equal(lesson.progress({ checked: true, answers: all, finish: false }), 80);
assert.equal(lesson.progress({ checked: true, answers: all, finish: true }), 100);
assert.equal(lesson.progressText({}), "Fortschritt: 0 %");
assert.equal(lesson.progressText({ checked: true, answers: all, finish: false }), "Fortschritt: 80 %");
assert.equal(lesson.progressText({ checked: true, answers: all, finish: true }), "Fortschritt: 100 %");
assert(glossary.includes('begriff: "DHCP"'));
const lf3 = catalog.slice(catalog.indexOf('{ id: "lf3"'), catalog.indexOf('{ id: "lf4"'));
assert(lf3.includes('{ id: "lf3-dhcp", typ: "lektion", titel: "DHCP: automatische Konfiguration nachvollziehen"'));
assert(lf3.includes('page: "lf3-dhcp", status: "verfuegbar", datei: "module/lf3-dhcp.html"'));
for (const id of ["lf3-client-anbindung", "lf3-ipv4-konfiguration", "lf3-ipv4", "lf3-netzmaske", "lf3-subnetting"]) assert(lf3.includes('id: "' + id + '"'), id + " bleibt erhalten");
assert.equal((lf3.match(/id: "lf3-dhcp"/g) || []).length, 1);
assert(catalog.includes('titel: "Netzwerkgrundlagen und Client-Anbindung", status: "verfuegbar"'));
console.log("lf3-dhcp.test.js: PASS — HTML, Fortschritt, leerer Check, richtige/falsche Antworten, Glossar und LF3-Katalog");
