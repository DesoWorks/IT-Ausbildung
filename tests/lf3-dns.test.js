"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const lesson = require(path.join(root, "js/lf3-dns.js"));
const html = fs.readFileSync(path.join(root, "module/lf3-dns.html"), "utf8");
const catalog = fs.readFileSync(path.join(root, "js/module-daten.js"), "utf8");
const glossary = fs.readFileSync(path.join(root, "js/glossar-daten.js"), "utf8");
const source = fs.readFileSync(path.join(root, "js/lf3-dns.js"), "utf8");

assert.equal(lesson.ID, "lf3-dns");
assert.equal(lesson.KEY, "it-ausbildung.lf3-dns.v1");
assert.deepEqual(lesson.STEPS, ["start", "case", "exercise", "finish"]);
assert.equal(lesson.QUESTIONS.length, 4);
for (const q of lesson.QUESTIONS) {
  assert.equal(q.options.filter(o => o.id === q.correct).length, 1, q.id + " hat genau eine richtige Option");
  assert(q.options.every(o => o.feedback.length > 20), q.id + " erklärt jede Option");
  const c = q.options.find(o => o.id === q.correct).label.length;
  const maxOther = Math.max(...q.options.filter(o => o.id !== q.correct).map(o => o.label.length));
  assert(c <= maxOther + 5, q.id + ": richtige Antwort nicht auffällig länger");
}
const pos = lesson.QUESTIONS.map(q => q.options.findIndex(o => o.id === q.correct));
assert(new Set(pos).size > 1, "richtige Antwort nicht immer an derselben Position");
assert(!pos.every(p => p === 0), "richtige Antwort nicht immer an erster Stelle");
assert(html.includes('<body data-page="lf3-dns"'));
assert(html.includes("DNS: Namen und IP-Adressen unterscheiden"));
for (const step of ['data-step="start"', 'data-step="case"', 'data-step="exercise"', 'data-step="finish"']) assert(html.includes(step));
assert(html.includes('href="../glossar.html?von=lf3-dns.html"'));
assert(html.includes('href="lf3-dhcp.html"') && html.includes('href="lf3-ipv4-konfiguration.html"'));
assert(html.includes("Fiktiver Hinweis") && html.includes("Mira-01") && html.includes("wiki.lernnetz.test") && html.includes("192.168.10.40") && html.includes("192.168.10.2"));
assert(html.includes("beweist keine Erreichbarkeit"));
assert(html.includes("Fortschritt: 0 %"));
assert(!html.includes("von 5 Schritten"));
assert(!/<input[^>]*\schecked/.test(html), "keine vorausgewählte Antwort");
assert(html.trim().endsWith("</html>"));
const order = ["module-daten", "fortschritt", "navigation", "glossar-daten", "anzeige-glossar", "version", "lf3-dns"].map(n => html.indexOf("../js/" + n + ".js"));
assert(order.every((v, i) => v > -1 && (i === 0 || order[i - 1] < v)), "Skriptreihenfolge");
assert(source.includes('input[name="\' + q.id + \'"]:checked'), "check() liest nur :checked Radios");
assert(source.includes("hide(); save(); update();"), "Ergebnisbox wird bei Antwortänderung ausgeblendet");
assert.equal(lesson.evaluate({}).empty, lesson.QUESTIONS.length);
assert.equal(lesson.evaluate({}).allCorrect, false);
assert.equal(lesson.evaluate({}).results[0].optionId, "");
const all = Object.fromEntries(lesson.QUESTIONS.map(q => [q.id, q.correct]));
assert.equal(lesson.evaluate(all).correct, lesson.QUESTIONS.length);
assert.equal(lesson.evaluate(all).allCorrect, true);
const wrong = { ...all, q1: lesson.QUESTIONS[0].options.find(o => o.id !== lesson.QUESTIONS[0].correct).id };
assert.equal(lesson.evaluate(wrong).wrong, 1);
assert.equal(lesson.evaluate(wrong).allCorrect, false);
assert(lesson.evaluate(wrong).results[0].feedback.length > 20);
assert.equal(lesson.progress({}), 0);
assert.equal(lesson.progress({ checked: true, answers: all, finish: false }), 80);
assert.equal(lesson.progress({ checked: true, answers: all, finish: true }), 100);
assert.equal(lesson.progressText({}), "Fortschritt: 0 %");
assert.equal(lesson.progressText({ checked: true, answers: all, finish: false }), "Fortschritt: 80 %");
assert.equal(lesson.progressText({ checked: true, answers: all, finish: true }), "Fortschritt: 100 %");
assert(glossary.includes('begriff: "DNS"'));
const lf3 = catalog.slice(catalog.indexOf('{ id: "lf3"'), catalog.indexOf('{ id: "lf4"'));
assert(lf3.includes('{ id: "lf3-dns", typ: "lektion", titel: "DNS: Namen und IP-Adressen unterscheiden"'));
assert(lf3.includes('page: "lf3-dns", status: "verfuegbar", datei: "module/lf3-dns.html"'));
assert(lf3.indexOf('id: "lf3-dhcp"') > -1 && lf3.indexOf('id: "lf3-dns"') > lf3.indexOf('id: "lf3-dhcp"'), "DNS steht nach DHCP");
for (const id of ["lf3-client-anbindung", "lf3-ipv4-konfiguration", "lf3-dhcp", "lf3-ipv4", "lf3-netzmaske", "lf3-subnetting"]) assert(lf3.includes('id: "' + id + '"'), id + " bleibt erhalten");
assert.equal((lf3.match(/id: "lf3-dns"/g) || []).length, 1);
assert(catalog.includes('titel: "Netzwerkgrundlagen und Client-Anbindung", status: "verfuegbar"'));
console.log("lf3-dns.test.js: PASS — HTML, Fortschritt, leerer Check, richtige/falsche Antworten, Glossar und LF3-Katalog");
